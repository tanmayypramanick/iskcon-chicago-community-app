-- ---------------------------------------------------------------------------
-- 4. Weekly seva, through the real generator and the real RPCs.
--
--    Not a hand-written row with template_id set. A real service_templates row,
--    a real standing assignee, public.generate_service_instances, and then the
--    three authorised acts the temple named — closed, verified, confirmed —
--    each through the RPC a President would actually press.
--
--    Recurring instances carry posted_by null, so every one of those three is
--    the President's here. That is 202608040027's authority, not this file's
--    choice, and it is why the President appears in all three calls.
--
--    HOW LONG THE SEVA IS, AND WHY IT IS NOT ALWAYS TWO HOURS. 202608040070
--    moved the completion bar from a seva's start to its end, and the President
--    closes this occurrence out below, so its whole length has to be behind us
--    before the button will work. Two fixed hours from midnight meant this file
--    passed after 02:00 Chicago and failed before it.
--
--    The occurrence cannot be moved off today to escape that. The generator
--    only ever writes today forward, and section 8 reads this act back out of
--    the devotee's WEEK — a seva moved to yesterday would leave that window
--    entirely every time the suite ran on the first day of a Chicago week. So
--    the day stays and the length gives: the seva starts at midnight and runs
--    for as much of the day as has actually elapsed, capped at the two hours it
--    has always been. Any run after 02:00 is byte for byte the old fixture; a
--    run at 00:05 gets a five-minute seva that genuinely finished.
--
--    Every assertion about this act reads its length back out of seva_pe_facts
--    rather than repeating a literal, so the shorter seva is asserted exactly
--    as hard as the two-hour one and no expectation can quietly drift off it.
-- ---------------------------------------------------------------------------

create table public.seva_pe_facts (key text primary key, minutes integer not null);
grant select on public.seva_pe_facts to authenticated;

do $$
declare
  v_type uuid;
  v_today date := public.seva_mala_today();
  v_president uuid;
  v_template uuid;
  -- now() is the transaction's, so this is the same instant the completion bar
  -- is measured against further down. Whole minutes, and never zero, because
  -- service_templates_duration_minutes_check wants at least one.
  v_elapsed_minutes integer := floor(
    extract(epoch from (now() at time zone 'America/Chicago')::time) / 60.0)::integer;
  v_minutes integer := greatest(1, least(120, v_elapsed_minutes));
begin
  select service_types.id into v_type
  from public.service_types where service_types.name = 'Pot Washing';
  select ids.id into v_president from public.seva_pe_ids ids where ids.key = 'president';

  insert into public.seva_pe_facts (key, minutes) values ('weekly', v_minutes);

  insert into public.service_templates (
    service_type_id, day_of_week, days_of_week, start_time, duration_minutes,
    slots_needed, participation_mode, start_date, created_by, active
  ) values (
    v_type, extract(dow from v_today)::integer, array[0, 1, 2, 3, 4, 5, 6],
    time '00:00', v_minutes, 1, 'open', v_today, v_president, true
  ) returning id into v_template;

  insert into public.service_template_assignees (
    service_template_id, devotee_id, assigned_by, status, days_of_week
  )
  select v_template, ids.id, v_president, 'active', array[0, 1, 2, 3, 4, 5, 6]
  from public.seva_pe_ids ids where ids.key = 'weekly';

  perform public.generate_service_instances(1);
end;
$$;

do $$
declare
  v_assignment uuid;
  v_instance uuid;
  v_status text;
begin
  select assignments.id, instances.id into v_assignment, v_instance
  from public.service_assignments assignments
  join public.service_instances instances
    on instances.id = assignments.service_instance_id
  where assignments.devotee_id
        = (select ids.id from public.seva_pe_ids ids where ids.key = 'weekly')
    and instances.template_id is not null
    and instances.date = public.seva_mala_today();

  if v_assignment is null then
    raise exception 'The generator did not place the weekly devotee on today''s instance.';
  end if;

  -- As generated: confirmed, self-reported, unconfirmed. Which is to say the
  -- state every recurring assignment in the temple is in right now.
  select public.seva_points_status(
           assignments.status, assignments.attendance, assignments.verification)
  into v_status
  from public.service_assignments assignments where assignments.id = v_assignment;
  if v_status <> 'awaiting_completion' then
    raise exception 'A freshly generated weekly assignment reads % rather than awaiting_completion.',
      v_status;
  end if;

  insert into public.seva_pe_acts (key, assignment_id) values ('weekly', v_assignment);
end;
$$;

