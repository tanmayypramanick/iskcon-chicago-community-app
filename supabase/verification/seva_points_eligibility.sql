-- Every kind of waiting counts as waiting. A devotee blocked on completion and
-- a devotee blocked on verification are as much in the queue as one blocked on
-- the attendance mark, and a pending count that quietly omits either is worse
-- than no pending count at all — it tells a devotee their seva simply vanished.
do $$
declare
  v_who text;
  v_expected text;
  v_acts integer;
  v_minutes integer;
  v_status text;
begin
  foreach v_who in array array['unclosed', 'selfsaid'] loop
    v_expected := case v_who
      when 'unclosed' then 'awaiting_completion'
      else 'awaiting_verification'
    end;
    perform set_config('request.jwt.claim.sub',
      (select ids.id::text from public.seva_pe_ids ids where ids.key = v_who), true);

    select mine.pending_acts, mine.pending_minutes into v_acts, v_minutes
    from public.my_seva_mala('week') mine;
    if v_acts <> 1 or v_minutes <> 120 then
      raise exception '% is told % acts and % minutes are waiting rather than one and 120.',
        v_who, v_acts, v_minutes;
    end if;

    select acts.points_status into v_status from public.my_seva_acts() acts;
    if v_status <> v_expected then
      raise exception '% is told their act is % rather than %.', v_who, v_status, v_expected;
    end if;
  end loop;
end;
$$;

