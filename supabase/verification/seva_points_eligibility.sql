  select profile.pending_hours, profile.counted_hours
  into v_hours, v_score
  from public.my_seva_profile() profile where profile.window_kind = 'week';
  if v_hours <> 2.00 then
    raise exception 'The waiting seva shows % hours rather than two.', v_hours;
  end if;
  if v_score <> 0.00 then
