    raise exception 'The week shows % cents given rather than %.',
      v_row.giving_cents, 7500 + v_in_week * 2500;
  end if;
  if v_row.gifts <> 1 + v_in_week then
    raise exception 'The week shows % gifts rather than %.', v_row.gifts, 1 + v_in_week;
