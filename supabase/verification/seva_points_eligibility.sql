-- ---------------------------------------------------------------------------
-- 1. The rule, over its entire domain.
--
--    Eighty combinations, three invariants. The expectations are written as the
--    temple's sentence rather than as a copy of the function's branches, so a
--    reordering that changes an answer is caught by the third invariant and a
--    widening by the first.
-- ---------------------------------------------------------------------------

do $$
declare
  v_status text;
  v_attendance text;
  v_verification text;
  v_result text;
  v_should_count boolean;
  v_should_refuse boolean;
  v_seen integer := 0;
begin
  foreach v_status in array array[
    'assigned', 'confirmed', 'completed', 'no_show', 'withdrawn'
  ] loop
    foreach v_attendance in array array['served', 'absent', 'excused', '(null)'] loop
      foreach v_verification in array array[
        'self_report', 'live_timer', 'qr_scan', 'member_verified'
      ] loop
        v_seen := v_seen + 1;
        v_result := public.seva_points_status(
          v_status, nullif(v_attendance, '(null)'), v_verification
        );

        -- The temple's sentence, restated: completed, and verified, and served.
        v_should_count :=
          v_status = 'completed'
          and v_attendance = 'served'
          and v_verification in ('live_timer', 'qr_scan', 'member_verified');

        if (v_result = 'counted') <> v_should_count then
          raise exception
            'points_status(%, %, %) is % — counted should be %.',
            v_status, v_attendance, v_verification, v_result, v_should_count;
        end if;

        -- Somebody said they were not there.
        v_should_refuse :=
          v_status in ('no_show', 'withdrawn')
          or v_attendance in ('absent', 'excused');

        if (v_result = 'not_served') <> v_should_refuse then
          raise exception
            'points_status(%, %, %) is % — not_served should be %.',
            v_status, v_attendance, v_verification, v_result, v_should_refuse;
        end if;

        -- Everything else is a queue, never a fourth kind of verdict.
        if not v_should_count and not v_should_refuse
          and v_result not in (
            'awaiting_completion', 'awaiting_verification', 'awaiting_confirmation')
        then
          raise exception
            'points_status(%, %, %) is %, which is neither counted, refused, nor waiting.',
            v_status, v_attendance, v_verification, v_result;
        end if;

        -- Whatever it says, it says something a devotee can read.
        if public.seva_points_note(v_result) is null then
          raise exception 'points_status % has no sentence to show a devotee.', v_result;
        end if;
      end loop;
    end loop;
  end loop;

  if v_seen <> 80 then
    raise exception 'The cross product was % combinations rather than eighty.', v_seen;
  end if;
end;
$$;

-- The order of the branches: an act blocked on two things reports the earliest
-- one somebody can act on, not whichever branch happened to be typed first.
