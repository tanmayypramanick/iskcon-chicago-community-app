      ('unclosed', 'awaiting_completion',   0.0,   0.0, 120.0),
      ('noshow',   'not_served',            0.0,   0.0, 120.0),
      ('orphan',   'awaiting_confirmation', 0.0,   0.0, 120.0),
      ('timer',    'counted',               0.7,  84.0, 120.0),
      ('weekly',   'counted',               1.0, v_weekly, v_weekly),
      -- 480 credited minutes shared over five acts, so each is worth 0.8 of
      -- itself. If the waiting act spent cap, this would be 80 rather than 96.
      ('c1',       'counted',               1.0,  96.0, 120.0),
      ('c6',       'awaiting_confirmation', 0.0,   0.0, 120.0)
    ) as spec(key, points_status, quality, weighted, served)
  loop
    select acts.points_status, acts.quality, acts.weighted_minutes, acts.raw_minutes
    into v_status, v_quality, v_weighted, v_raw
    from public.seva_mala_acts() acts
    join public.seva_pe_acts ids on ids.assignment_id = acts.assignment_id
    where ids.key = v_case.key;

    if v_status is distinct from v_case.points_status then
      raise exception '% reads % rather than %.', v_case.key, v_status, v_case.points_status;
    end if;
    if v_quality is distinct from v_case.quality then
      raise exception '% earns quality % rather than %.', v_case.key, v_quality, v_case.quality;
    end if;
    if v_weighted is distinct from v_case.weighted then
      raise exception '% is worth % weighted minutes rather than %.',
        v_case.key, v_weighted, v_case.weighted;
    end if;

    -- The hours survive whatever the points did. This is the difference between
    -- "we are still confirming it" and "it never happened".
    if v_raw is distinct from v_case.served then
      raise exception '% recorded % minutes served rather than %.',
        v_case.key, v_raw, v_case.served;
    end if;
  end loop;
end;
$$;

-- And at the level the scoring actually reads: the devotees whose seva is
-- waiting have no score row at all, while the three who satisfied all three
-- conditions do.
do $$
declare
  v_who text;
  v_rows integer;
  v_lifetime uuid;
  v_credited numeric;
begin
  select periods.id into v_lifetime
  from public.seva_mala_periods periods where periods.period_kind = 'lifetime';

  foreach v_who in array array['unmarked', 'absent', 'excused', 'selfsaid', 'unclosed',
                               'noshow', 'orphan'] loop
    select count(*) into v_rows
    from public.period_scores scores
    join public.seva_pe_ids ids on ids.id = scores.devotee_id
    where scores.period_id = v_lifetime and ids.key = v_who;
    if v_rows <> 0 then
      raise exception '% was scored despite earning no points.', v_who;
    end if;
  end loop;

  foreach v_who in array array['alldone', 'timer', 'weekly', 'capped'] loop
    select scores.credited_minutes into v_credited
    from public.period_scores scores
    join public.seva_pe_ids ids on ids.id = scores.devotee_id
    where scores.period_id = v_lifetime and ids.key = v_who;
    if v_credited is null or v_credited <= 0 then
      raise exception '% satisfied all three conditions and was credited %.', v_who, v_credited;
    end if;
  end loop;

  -- Alldone: three counted acts today plus one in January, and nothing for the
  -- act still waiting. 120 + 120 + 60 + 120.
  select scores.credited_minutes into v_credited
  from public.period_scores scores
  join public.seva_pe_ids ids on ids.id = scores.devotee_id
  where scores.period_id = v_lifetime and ids.key = 'alldone';
  if v_credited <> 420 then
    raise exception 'Alldone was credited % minutes rather than 420.', v_credited;
  end if;

  -- The cap is a claim about the physical day, and a waiting act is not part
  -- of it. Ten hours served, eight credited — not eight shared over twelve.
  select scores.credited_minutes into v_credited
  from public.period_scores scores
  join public.seva_pe_ids ids on ids.id = scores.devotee_id
  where scores.period_id = v_lifetime and ids.key = 'capped';
  if v_credited <> 480 then
    raise exception
      'Ten hours served against an eight-hour cap credited % minutes rather than 480.',
      v_credited;
  end if;

  -- The scarcity weight is 1.0 with a single service type, so every weighted
  -- figure above is the quality multiplier and nothing else.
  if exists (select 1 from public.seva_type_weights where weight <> 1.0) then
    raise exception 'A single service type produced a scarcity weight other than 1.0.';
  end if;
end;
$$;

