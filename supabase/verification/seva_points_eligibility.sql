-- The case the live timer creates on every act it writes: the devotee posted
-- the seva and served it. They hold the authority over it — they may close it
-- out and they may mark their own attendance — and they are still not somebody
-- other than themselves. Without this the whole verification requirement is one
-- devotee's two taps.
select set_config('request.jwt.claim.sub',
  (select ids.id::text from public.seva_pe_ids ids where ids.key = 'soloist'), true);

do $$
declare
  v_assignment uuid;
  v_status text;
begin
  select acts.assignment_id into v_assignment
  from public.seva_pe_acts acts where acts.key = 'solo';

  begin
    perform public.verify_seva_assignment(v_assignment);
    raise exception 'The devotee who posted their own seva verified themselves.';
  exception when others then
    if position('other than you' in sqlerrm) = 0 then raise; end if;
