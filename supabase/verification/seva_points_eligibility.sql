-- Functional verification for 202608040057_seva_points_eligibility.sql.
--
-- Rolled back at the end. Every local is prefixed v_ so it can never shadow a
-- column name. Anything that must be refused is attempted as the devotee who
-- would really attempt it, under `set local role authenticated`, so the row
-- level security policies, the column grants and the permission checks are what
-- is being tested rather than superuser rights waving everything through.
--
-- ---------------------------------------------------------------------------
-- What is being proved.
--
-- The temple's sentence is a conjunction of three things, and the whole point
-- of this file is that it is a conjunction: completed AND verified AND served.
-- So section 2 does not check the six cases somebody thought of. It walks the
-- entire cross product — five assignment statuses by four attendance values by
-- four verification levels, eighty combinations — and asserts three invariants
-- over all eighty at once:
--
--   counted        exactly when status is completed, attendance is served, and
--                  verification is live_timer, qr_scan or member_verified
--   not_served     exactly when somebody said they were not there
--   awaiting_*     everything else, and never anything else
--
-- Stated that way, a mutation that widens the rule by one value fails, and it
-- fails whether or not anybody thought to write a case for that value.
--
-- The cast, and what each one is for:
--
--   poster    ...01  posts the ordinary seva; may verify and confirm it
--   president ...02  app.view_all; the only authority over weekly seva
--   alldone   ...03  completed + member_verified + served. Earns. Also carries
--                    a pending act, a custom-named seva, a January act and two
--                    gifts, so the windows and the breakdown have something to
--                    be wrong about
--   unmarked  ...04  everything but the attendance mark. THE row this feature
--                    exists for: zero points, and told so in words
--   absent    ...05  marked absent
--   excused   ...06  marked excused
--   selfsaid  ...07  completed and served, but only they say it happened
--   unclosed  ...08  verified and served on a seva nobody closed out
--   noshow    ...09  marked served on an assignment recorded as a no-show
--   weekly    ...10  recurring seva, generated by the real generator from a
--                    real template, taken through the real RPCs
--   timer     ...11  a live timer nobody stopped, since confirmed: 0.7, not 0
--   orphan    ...12  a pending act on a seva with no poster, so the President's
--                    queue can be proved wider than the poster's
--   other     ...13  an ordinary devotee with no seva at all, who must be able
--                    to read nothing about anybody
--   soloist   ...15  posts a seva and serves it themselves, which is what the
--                    live timer does on every act it creates. Holds the
--                    authority over their own seva and must still not be the
--                    someone in "someone verified it"
--   capped    ...14  ten hours in one Chicago day against an eight-hour cap,
--                    plus one act still waiting. The waiting act must spend no
--                    cap at all: if it did, confirming Thursday's seva would
--                    silently move Tuesday's credit down
--
-- The final row must read: seva points eligibility verification passed

